# Numeric columns that index rather than measure, and so are never recast.
# `year` is the only one in the shipped objects; `vintage` is character there
# but integer in some user models, so it is guarded too.
.recast_id_cols <- c("year", "vintage", "cluster")

# -- the declared recast contract -------------------------------------------- #
# `.defRecast` (generated by data-raw/recast_rules.R from the recast rules of
# data-raw/parameters.yml, over the columns `.col_param` resolved) says how each
# column of each slot behaves on each axis. One entry covers both directions,
# because every rule in the engine is defined both ways: `sum` sums going up
# and splits by weight going down.

#' Build the recast table from row-wise entries
#'
#' Five values a row -- class, slot, column, space rule, time rule -- so a
#' rule can be read off the generated file at a glance instead of counting
#' positions across five parallel vectors.
#' @noRd
.recast_rules <- function(...) {
  v <- c(...)
  stopifnot(length(v) %% 5L == 0L)
  m <- matrix(v, ncol = 5L, byrow = TRUE)
  data.frame(class = m[, 1L], slot = m[, 2L], column = m[, 3L],
             space = m[, 4L], time = m[, 5L], stringsAsFactors = FALSE)
}

#' The declared recast rule for one or more columns of a slot
#'
#' @param class,slot The object class and slot the columns belong to.
#' @param column Character vector of column names.
#' @param axis `"space"` or `"time"`.
#' @return A named character vector, one entry per `column`. `NA` where the
#'   column is not indexed on that axis, or where nothing is declared for it --
#'   `.recast_undeclared()` tells the two apart.
#' @noRd
.get_recast_rule <- function(class, slot, column, axis = c("space", "time")) {
  axis <- match.arg(axis)
  ref <- paste(.defRecast$class, .defRecast$slot, .defRecast$column, sep = "")
  i <- match(paste(class, slot, column, sep = ""), ref)
  stats::setNames(.defRecast[[axis]][i], column)
}

#' Columns of a slot carrying no declaration at all
#' @noRd
.recast_undeclared <- function(class, slot, column) {
  ref <- paste(.defRecast$class, .defRecast$slot, .defRecast$column, sep = "")
  column[is.na(match(paste(class, slot, column, sep = ""), ref))]
}

# --------------------------------------------------------------------------- #
# is_divisible(): what a region subset still needs before it can cut.
#
# The recast rule is declared per class, slot and column, and it is the
# arithmetic, not the decision. `weighted_mean`, `mean` and `copy` say the
# value is a rate, a price or an invariant: it holds for each child unchanged,
# so a cut that keeps part of a parent's children carries the declaration as
# it stands and needs nothing. `sum` says the value is a quantity, and there
# the rule is incomplete: it says the parent is the total of its children, not
# how a part of that total is apportioned. That takes a WEIGHT, and there is no
# defensible default -- dividing a demand or a fleet by area shares a city with
# a desert -- so the caller names it.
#
# Space and time ask for different things. On the time axis nothing is `sum`
# (a timeslice value is a rate), so no weight is ever wanted; what the time
# axis lacks is a declared rule for the columns that have none.
# --------------------------------------------------------------------------- #

# What a row still wants before a cut can act on it.
.DIV_NEEDS <- c(none = "", weight = "weight", rule = "rule")

.DIV_REASON <- c(
  carried = "a rate or an invariant: holds for every child",
  weight = paste("a quantity: name the weight to divide it by, or keep/drop",
                 "it"),
  ready = "a quantity, divided by the weight given",
  kept = "kept whole in every part",
  dropped = "left out of the cut",
  rule = "no rule declared, inferred or registered",
  none = "the rule has no downward meaning: keep or drop it")

# One row per value column, with where the rule came from and what it wants.
#' @noRd
.div_rows <- function(cols, cls = NA_character_, slot = NA_character_,
                      axis = "space") {
  cols <- setdiff(unique(cols), .AGG_ID_COLS)
  if (!length(cols)) {
    return(tibble::tibble(
      class = character(), slot = character(), column = character(),
      rule = character(), source = character(), needs = character(),
      weight = character(), ready = logical(), reason = character()))
  }
  rule <- if (is.na(cls) || is.na(slot)) {
    stats::setNames(rep(NA_character_, length(cols)), cols)
  } else {
    .get_recast_rule(cls, slot, cols, axis)
  }
  src <- ifelse(is.na(rule), NA_character_, "declared")
  todo <- is.na(rule)
  # The inference the declared contract was seeded from, and which the
  # aggregator still applies where the contract does not reach. Space only:
  # there is no timeframe twin of `.AGG_EXTENSIVE_RE`.
  if (any(todo) && identical(axis, "space")) {
    rule[todo] <- .agg_rules(cols[todo],
                             cls = if (is.na(cls)) NULL else cls,
                             slot = if (is.na(slot)) NULL else slot)
    src[todo] <- "inferred"
  }
  todo <- is.na(rule)
  if (any(todo)) {
    reg <- vapply(cols[todo], function(p) {
      e <- tryCatch(geoscales::get_geoscale_rule(p), error = function(e) NULL)
      if (is.null(e)) NA_character_ else as.character(e$rule)[1]
    }, character(1))
    rule[todo] <- reg
    src[todo] <- ifelse(is.na(reg), NA_character_, "registry")
  }
  out <- tibble::tibble(
    class = as.character(cls), slot = as.character(slot), column = cols,
    rule = unname(rule), source = unname(src),
    needs = .DIV_NEEDS[["rule"]], weight = NA_character_, ready = FALSE,
    reason = .DIV_REASON[["rule"]])
  known <- !is.na(out$rule)
  if (any(known)) {
    act <- geoscales::geoscale_rule_action(out$rule[known])
    carried <- known & FALSE
    carried[known] <- act$action == "replicate"
    quantity <- known & FALSE
    quantity[known] <- act$action == "split"
    nodir <- known & FALSE
    nodir[known] <- act$action == "none"
    out$needs[carried] <- .DIV_NEEDS[["none"]]
    out$ready[carried] <- TRUE
    out$reason[carried] <- .DIV_REASON[["carried"]]
    out$needs[quantity] <- .DIV_NEEDS[["weight"]]
    out$reason[quantity] <- .DIV_REASON[["weight"]]
    out$needs[nodir] <- .DIV_NEEDS[["rule"]]
    out$reason[nodir] <- .DIV_REASON[["none"]]
  }
  out
}

# A specification keyed on an object name or a class, then optionally on a
# column: list(SUP_COA = c(ava.up = "area"), supply = "population"), or the
# flat shorthand c("SUP_COA:ava.up" = "area"). Returns the value for one row
# and the key it came from, most specific first.
#' @noRd
.div_lookup <- function(spec, name, cls, column) {
  if (is.null(spec) || !length(spec)) return(NULL)
  get1 <- function(key, col) {
    if (!key %in% names(spec)) return(NULL)
    v <- spec[[key]]
    # A list holds one entry per column, each entry a weight name or shares.
    if (is.list(v)) {
      if (!is.null(names(v)) && col %in% names(v)) {
        return(list(value = v[[col]], key = paste0(key, ":", col)))
      }
      if (is.null(names(v)) && length(v) == 1L) {
        return(list(value = v[[1L]], key = key))
      }
      return(NULL)
    }
    # A NAMED NUMERIC is shares over the regions, so it belongs to the key as
    # a whole; a named character is one weight name per column.
    if (is.numeric(v) && length(v) > 1L) return(list(value = v, key = key))
    if (!is.null(names(v)) && any(nzchar(names(v)))) {
      if (!col %in% names(v)) return(NULL)
      return(list(value = v[[col]], key = paste0(key, ":", col)))
    }
    if (length(v) != 1L) {
      stop("`", key, "` must be one weight, one per column, or shares over ",
           "the regions", call. = FALSE)
    }
    list(value = v[[1L]], key = key)
  }
  flat <- function(key) {
    if (!key %in% names(spec)) return(NULL)
    list(value = spec[[key]], key = key)
  }
  cand <- list(
    if (!is.na(name)) function() flat(paste0(name, ":", column)),
    if (!is.na(name)) function() get1(name, column),
    function() flat(paste0(cls, ":", column)),
    function() get1(cls, column))
  for (f in cand) {
    if (is.null(f)) next
    hit <- f()
    if (!is.null(hit)) return(hit)
  }
  NULL
}

# Resolve the rows that want something against what the caller gave.
#' @noRd
.div_decide <- function(out, split_weight = NULL, keep = NULL, drop = NULL,
                        weights = NULL) {
  if (is.null(out) || !nrow(out)) return(out)
  as_spec <- function(x, what, bare_ok = FALSE) {
    if (is.null(x) || !length(x)) return(NULL)
    # `keep` and `drop` name the columns they settle, so a bare vector of keys
    # is their natural form; a weight has to say which key it is for.
    if (bare_ok && is.character(x) && is.null(names(x))) {
      return(stats::setNames(as.list(rep(TRUE, length(x))), x))
    }
    if (is.null(names(x)) || any(!nzchar(names(x)))) {
      stop("`", what, "` must be named: ", what,
           if (bare_ok) " = c(\"SUP_COA\")" else " = list(SUP_COA = \"area\")",
           call. = FALSE)
    }
    as.list(x)
  }
  sw <- as_spec(split_weight, "split_weight")
  kp <- as_spec(keep, "keep", bare_ok = TRUE)
  dp <- as_spec(drop, "drop", bare_ok = TRUE)
  nm <- if ("name" %in% names(out)) out$name else rep(NA_character_, nrow(out))
  used <- character()
  for (i in seq_len(nrow(out))) {
    if (out$ready[i] && !nzchar(out$needs[i])) next
    d <- .div_lookup(dp, nm[i], out$class[i], out$column[i])
    if (!is.null(d)) {
      used <- c(used, d$key)
      out$needs[i] <- .DIV_NEEDS[["none"]]
      out$ready[i] <- TRUE
      out$reason[i] <- .DIV_REASON[["dropped"]]
      next
    }
    k <- .div_lookup(kp, nm[i], out$class[i], out$column[i])
    if (!is.null(k)) {
      used <- c(used, k$key)
      out$needs[i] <- .DIV_NEEDS[["none"]]
      out$ready[i] <- TRUE
      out$reason[i] <- .DIV_REASON[["kept"]]
      next
    }
    if (!identical(out$needs[i], .DIV_NEEDS[["weight"]])) next
    w <- .div_lookup(sw, nm[i], out$class[i], out$column[i])
    if (is.null(w)) next
    used <- c(used, w$key)
    lab <- if (is.character(w$value)) {
      as.character(w$value)[1]
    } else {
      "shares"
    }
    if (is.character(w$value) && length(weights) &&
        !lab %in% weights) {
      stop("`split_weight` = \"", lab, "\" is not a weight column of the ",
           "geoscale; one of: ", paste(weights, collapse = ", "), call. = FALSE)
    }
    out$weight[i] <- lab
    out$needs[i] <- .DIV_NEEDS[["none"]]
    out$ready[i] <- TRUE
    out$reason[i] <- .DIV_REASON[["ready"]]
  }
  given <- unique(c(names(sw), names(kp), names(dp)))
  unmatched <- setdiff(given, unique(c(used, sub(":.*$", "", used))))
  # a key given per column matches through its parent key, so only a key that
  # resolved nothing at all is reported
  unmatched <- unmatched[!vapply(unmatched, function(g)
    any(startsWith(used, paste0(g, ":"))), logical(1))]
  if (length(unmatched)) attr(out, "unmatched") <- unmatched
  out
}

# Every value column of one object, slot by slot.
#' @noRd
.div_object <- function(object, axis = "space", slots = NULL) {
  cls <- class(object)[1]
  sl <- if (is.null(slots)) methods::slotNames(object) else slots
  rows <- lapply(sl, function(s) {
    v <- tryCatch(methods::slot(object, s), error = function(e) NULL)
    if (!is.data.frame(v) || !ncol(v)) return(NULL)
    num <- names(v)[vapply(v, is.numeric, logical(1))]
    # A declared-but-empty column is contract, not data: the object shapes
    # report what the object CARRIES. `is_divisible()` with no object is where
    # the whole contract lives.
    num <- num[vapply(num, function(cn) any(!is.na(v[[cn]])), logical(1))]
    .div_rows(num, cls = cls, slot = s, axis = axis)
  })
  do.call(rbind, rows)
}

# The slots of one object that carry a region code the model does not declare,
# i.e. a declaration sitting above the model's own regions.
#' @noRd
.div_coarse_slots <- function(object, atoms, finest = NA_character_) {
  hit <- character()
  r <- tryCatch(as.character(methods::slot(object, "region")),
                error = function(e) character())
  gf <- tryCatch(as.character(methods::slot(object, "geoframe")),
                 error = function(e) character())
  # A `@geoframe` naming the model's OWN finest frame is not a declaration
  # above the regions -- it is the default said out loud.
  coarse_gf <- length(gf) > 0L && nzchar(gf[1]) && !identical(gf[1], finest)
  coarse_obj <- (length(r) > 0L && any(nzchar(r) & !r %in% atoms)) || coarse_gf
  for (s in methods::slotNames(object)) {
    v <- tryCatch(methods::slot(object, s), error = function(e) NULL)
    if (!is.data.frame(v) || !nrow(v)) next
    if (!"region" %in% names(v)) {
      # A table with no region of its own inherits the object's declaration.
      if (coarse_obj) hit <- c(hit, s)
      next
    }
    rg <- as.character(v$region)
    if (any(!is.na(rg) & nzchar(rg) & !rg %in% atoms)) hit <- c(hit, s)
  }
  unique(hit)
}

# The model's own regions. `@config@region` is empty on a model assembled from
# a geoscale alone, and an empty atom set would make every declaration look
# coarse, so the geoscale's finest frame stands in for it.
#' @noRd
.div_model_atoms <- function(object) {
  a <- tryCatch(as.character(object@config@region), error = function(e) NULL)
  a <- a[!is.na(a) & nzchar(a)]
  if (length(a)) return(a)
  gs <- tryCatch(object@config@geoscale, error = function(e) NULL)
  if (!is.null(gs) && is_geoscale(gs)) {
    return(as.character(geoscales::geoscale_regions(gs)))
  }
  character()
}

#' What a region subset still needs before it can cut
#'
#' Reports, column by column, what a partial selection of a region group does
#' to a value declared at the group. The recast rule declared for the column is
#' the arithmetic: a rate, a price or a region-invariant scalar
#' (`weighted_mean`, `mean`, `copy`) holds for each child unchanged, so the
#' declaration is carried as it stands and the row is ready. A quantity (`sum`)
#' is not settled by its rule -- the rule says the parent is the total of its
#' children, not how a part of that total is apportioned -- so the row asks for
#' a **weight**, and there is no default: dividing a demand or a fleet by area
#' shares a city with a desert.
#'
#' Name the weight with `split_weight`, or settle a column without one through
#' `keep` (hold the value whole in every part) or `drop`. All three are keyed
#' on an object name or a class, optionally per column:
#' `split_weight = list(SUP_COA = c(ava.up = "area"), demand = "population")`,
#' or the flat shorthand `c("SUP_COA:ava.up" = "area")`, most specific first.
#' A weight is a weight column declared on the geoscale (see
#' [geoscales::geoscale_weights()]) or a named numeric of shares over the kept
#' regions.
#'
#' `attr(x, "ready")` is `TRUE` when every row is settled, which is the test a
#' region subset makes before it refuses; `attr(x, "unmatched")` names keys
#' that matched nothing.
#'
#' On a `model` it reports only the columns that model declares **above** its
#' own regions -- usually a handful -- rather than the whole contract.
#'
#' The time axis asks for nothing of the kind: no time rule is `sum`, since a
#' timeslice value is a rate. What it reports instead is which columns declare
#' no time rule at all, as `needs = "rule"`.
#'
#' @param object a `model`, a `repository`, any model object (a `technology`,
#'   a `supply`, ...), or `NULL` for the whole declared contract.
#' @param axis `"space"` (the default) or `"time"`. The space axis falls back
#'   to the aggregator's own inference where nothing is declared; the time
#'   axis does not.
#' @param column optional character vector of column names to report on
#'   directly, with no class or slot to declare them.
#' @param split_weight the weight each quantity is divided by, keyed as
#'   described above. A geoscale weight column name, or a named numeric of
#'   shares over the kept regions.
#' @param keep,drop keys whose columns are settled without a weight: held
#'   whole in every part, or left out of the cut.
#'
#' @returns A tibble with one row per column: `class`, `slot`, `column`,
#'   `rule` (the declared recast arithmetic), `source` (`"declared"`,
#'   `"inferred"` or `"registry"`), `needs` (`""`, `"weight"` or `"rule"`),
#'   `weight` (what was given, or `"shares"` for explicit ones), `ready` and
#'   `reason`. Every shape built from objects adds the object `name` in front.
#'   See `attr(x, "ready")` and `attr(x, "unmatched")`.
#'
#' @examples
#' # the declared contract
#' is_divisible()
#'
#' # single columns, with no class to declare them
#' is_divisible(column = c("cap.up", "cost"))
#'
#' # a quantity asks for a weight; a rate does not
#' is_divisible(column = c("ava.up", "cost"))
#' @export
is_divisible <- function(object = NULL, axis = c("space", "time"),
                         column = NULL, split_weight = NULL, keep = NULL,
                         drop = NULL) {
  axis <- match.arg(axis)
  wts <- NULL
  if (!is.null(object)) {
    gs0 <- tryCatch(object@config@geoscale, error = function(e) NULL)
    if (!is.null(gs0) && is_geoscale(gs0)) {
      wts <- tryCatch(geoscales::geoscale_weights(gs0), error = function(e) NULL)
    }
  }
  fin <- function(d) {
    if (is.null(d) || !nrow(d)) {
      d <- .div_rows(character())
      attr(d, "ready") <- TRUE
      return(d)
    }
    d <- .div_decide(d, split_weight, keep, drop, weights = wts)
    attr(d, "ready") <- all(d$ready)
    d
  }
  if (!is.null(column)) return(fin(.div_rows(column, axis = axis)))
  if (is.null(object)) {
    rows <- lapply(seq_len(nrow(.defRecast)), function(i) {
      .div_rows(.defRecast$column[i], cls = .defRecast$class[i],
                slot = .defRecast$slot[i], axis = axis)
    })
    return(fin(do.call(rbind, rows)))
  }
  if (inherits(object, "model") || inherits(object, "repository")) {
    atoms <- if (inherits(object, "model")) .div_model_atoms(object) else NULL
    gs <- tryCatch(object@config@geoscale, error = function(e) NULL)
    finest <- if (!is.null(gs) && is_geoscale(gs)) {
      as.character(geoscales::geoscale_geoframes(gs, finest = TRUE))[1]
    } else {
      NA_character_
    }
    ob <- getObject(object)
    rows <- lapply(names(ob), function(nm) {
      o <- ob[[nm]]
      sl <- if (is.null(atoms) || !length(atoms)) {
        NULL
      } else {
        .div_coarse_slots(o, atoms, finest)
      }
      if (!is.null(sl) && !length(sl)) return(NULL)
      d <- .div_object(o, axis = axis, slots = sl)
      if (is.null(d) || !nrow(d)) return(NULL)
      tibble::add_column(d, name = nm, .before = 1L)
    })
    return(fin(do.call(rbind, rows)))
  }
  d <- .div_object(object, axis = axis)
  onm <- tryCatch(as.character(object@name)[1], error = function(e) NA_character_)
  if (!is.null(d) && nrow(d) && !is.na(onm) && nzchar(onm)) {
    d <- tibble::add_column(d, name = onm, .before = 1L)
  }
  fin(d)
}

#' Recast rules for the solution variables, by role
#'
#' DUPLICATE of `recast_by_role` in `data-raw/DATASET.R`, which resolves these
#' into `.variables` before the package is loadable. `test-recast-contract.R`
#' asserts the two agree, which is what catches a drift.
#'
#' `sum` on the time axis means "sum at the child/target weight ratio", which
#' is what `.aggregate_timeframe_df()` applies: a per-slice solved value is
#' already scaled by `share`, and `Sum(share * weight) == 1`, so the annual
#' total is `Sum(value * weight)`. It is a plain sum between full calendars,
#' where every weight is 1.
#' @noRd
.VARIABLE_RECAST_BY_ROLE <- list(
  source        = c(space = "sum",          time = "sum"),
  sink          = c(space = "sum",          time = "sum"),
  activity      = c(space = "sum",          time = "sum"),
  balance       = c(space = "sum",          time = "sum"),
  stock         = c(space = "sum",          time = "last"),
  capacity      = c(space = "sum",          time = NA),
  cost          = c(space = "sum",          time = NA),
  interregional = c(space = "sum_external", time = "sum")
)

#' @noRd
.VARIABLE_RECAST_RULES <- list(
  space = c("sum", "weighted_mean", "copy", "sum_external"),
  time = c("sum", "weighted_mean", "copy", "last")
)

#' The declared recast rule for one or more solution variables
#'
#' The results-side twin of [.get_recast_rule()]. Aggregation ONLY: a solution
#' cannot be split into a finer calendar or geometry, so `axis = "down"` is an
#' error rather than an inverse -- `.recast_rules()`'s bidirectional contract
#' ("sum sums going up and splits by weight going down") does not hold here.
#'
#' @param variable Character vector of variable names.
#' @param axis `"space"` or `"time"`.
#' @return A named character vector, one entry per `variable`. `NA` where the
#'   variable is not indexed on that axis (no `cost` or `capacity` variable has
#'   a timeslice; `vObjective` has neither), and `NA` for a name that is not a
#'   declared variable.
#' @noRd
.get_variable_recast_rule <- function(variable, axis = c("space", "time")) {
  if (identical(axis, "down") || identical(axis, "split")) {
    stop("recast rules for solution variables are aggregation-only: a solved ",
         "result cannot be split into a finer calendar or geometry.",
         call. = FALSE)
  }
  axis <- match.arg(axis)
  key <- paste0("recast_", axis)
  v <- tryCatch(.variables, error = function(e) NULL)
  out <- vapply(variable, function(nm) {
    x <- v[[nm]]
    if (is.null(x)) return(NA_character_)
    as.character(x[[key]])[1]
  }, character(1))
  stats::setNames(out, variable)
}

#' Recast a model onto another calendar
#'
#' Moves a model's time-varying data from the calendar it was written against
#' onto `calendar`, so the model can be built and solved at another time
#' resolution. The time mirror of [subset_model_regions()] and
#' [aggregate_model_regions()].
#'
#' Every timeslice-indexed value in energyRt is a rate: the equations multiply
#' it by the timeslice weight to obtain an annual quantity. Aggregating
#' therefore takes the weighted mean, which conserves the weighted annual
#' total exactly, and disaggregating copies the rate into each child timeslice.
#' `rules` overrides this per column where a value is not a rate (a declared
#' quantity to be summed, a standard deviation).
#'
#' Rows are recast by their own timeframe, not by their table: only rows at the
#' source calendar's leaf timeframe move. A row declared at `ANNUAL`, or at any
#' timeframe `calendar` also has, is left exactly as it is.
#'
#' A `@timeframe` naming a timeframe `calendar` does not have falls back to the
#' finest timeframe that survives, and is reported -- otherwise the model
#' references a timeframe its calendar cannot resolve.
#'
#' @section Comparability:
#' A recast model is not a smaller answer to the same question. Collapsing
#' timeslices removes the variation inside them, which is what a model prices:
#' peaks flatten, variable resources become firmer than they are, and storage
#' loses the cycle it was built to serve. Its dispatch, costs and objective are
#' its own. Use it to run, plot and teach the shape of a solution, not to
#' report the source model's numbers.
#'
#' @param object a [model].
#' @param calendar the target [calendar][class-calendar]; coarser or finer than
#'   the model's own.
#' @param rules optional named character vector of
#'   [timescales::CALENDAR_RULES] keyed by value column, overriding the rate
#'   default for those columns (e.g. `c(demand = "sum")`).
#' @param year model year used to materialise both calendars on a shared
#'   datetime grid. `NULL` (default) takes the model's first horizon milestone.
#'   It matters only where the calendars align to real dates (days of the year,
#'   weekdays), and then only across a leap year.
#' @param verbose print per-table messages.
#'
#' @return the recast [model], carrying `calendar`.
#' @family interpolation
#' @export
#' @examples
#' mod <- newModel("TOPIA", data = topia$modules$electricity$repo,
#'                 calendar = topia$modules$calendars$s4_h24,
#'                 region = topia$modules$electricity$regions,
#'                 horizon = topia$modules$horizons$BY2025,
#'                 discount = 0.05)
#'
#' # 96 hourly timeslices collapse to 4 seasons: the same model, small enough
#' # to solve in a second
#' light <- recast_model_calendar(mod, calendar = calendars$s4)
#' getCalendar(light)
#'
#' # the hourly demand profile, and the four seasonal rates it becomes
#' dem <- getObject(light, name = "DEM_ELC", drop = TRUE)
#' head(dem@demand)
recast_model_calendar <- function(object, calendar, rules = NULL, year = NULL,
                                  verbose = isVerbose()) {
  stopifnot(inherits(object, "model"))
  if (!methods::is(calendar, "calendar")) {
    stop("`calendar` must be an energyRt calendar; see newCalendar() and ",
         "the `calendars` catalog.", call. = FALSE)
  }
  check_package("timescales")
  if (!is.null(rules)) {
    if (!is.character(rules) || is.null(names(rules)) ||
        any(!nzchar(names(rules)))) {
      stop("`rules` must be a named character vector, keyed by value column ",
           "(e.g. c(demand = \"sum\")).", call. = FALSE)
    }
    bad <- setdiff(unname(rules), timescales::CALENDAR_RULES)
    if (length(bad)) {
      stop("unknown rule(s): ", paste(bad, collapse = ", "),
           ". Available: ", paste(timescales::CALENDAR_RULES, collapse = ", "),
           ".", call. = FALSE)
    }
  }
  src <- object@config@calendar
  if (!nrow(src@timetable)) {
    stop("the model carries no calendar to recast from.", call. = FALSE)
  }

  ts_src <- .ts_calendar(src)
  ts_tgt <- .ts_calendar(calendar)
  if (is.null(ts_src) || is.null(ts_tgt)) {
    stop("recasting needs both calendars to carry a timeframe below ANNUAL; ",
         "a model at annual resolution has no timeslices to recast.",
         call. = FALSE)
  }

  src_leaves <- as.character(src@timetable$timeslice)
  tgt_tfs <- .calendar_timeframes(calendar)
  finest <- tgt_tfs[length(tgt_tfs)]
  n_src <- length(src_leaves)
  n_tgt <- nrow(calendar@timetable)
  if (identical(n_src, n_tgt) && setequal(src_leaves,
                                          as.character(calendar@timetable$timeslice))) {
    .say("recast: the model already carries this calendar; nothing to do.")
    return(object)
  }
  rule_default <- if (n_tgt < n_src) "weighted_mean" else "copy"
  if (is.null(year)) year <- .recast_year(object)

  st <- list(tables = 0L, rows_in = 0L, rows_out = 0L, kept = 0L,
             tf = character(0), dropped = character(0))

  recast_el <- function(el) {
    if (methods::is(el, "repository")) {
      for (nm in names(el@data)) el@data[[nm]] <- recast_el(el@data[[nm]])
      return(el)
    }
    if (!isS4(el)) return(el)
    nm_el <- tryCatch(el@name, error = function(e) "<unnamed>")
    for (sn in .instance_slots(el)) {
      if (identical(sn, "misc")) next
      v <- methods::slot(el, sn)
      if (is.data.frame(v) && nrow(v) > 0L && "timeslice" %in% colnames(v)) {
        r <- .recast_table(v, ts_src = ts_src, ts_tgt = ts_tgt,
                           src_leaves = src_leaves, rule_default = rule_default,
                           rules = rules, year = year,
                           where = paste0(nm_el, "@", sn))
        if (!is.null(r$data)) {
          st$tables <<- st$tables + 1L
          st$rows_in <<- st$rows_in + nrow(v)
          st$rows_out <<- st$rows_out + nrow(r$data)
          st$kept <<- st$kept + r$kept
          if (length(r$dropped)) st$dropped <<- c(st$dropped, r$dropped)
          if (isTRUE(verbose)) {
            .say2(sprintf("  %-28s %6d -> %6d row(s)%s",
                            paste0(nm_el, "@", sn), nrow(v), nrow(r$data),
                            if (r$kept) paste0(" (", r$kept, " kept as declared)")
                            else ""))
          }
          methods::slot(el, sn) <- r$data
        }
        next
      }
      # the declarations: a timeframe the target does not have
      if (grepl("timeframe", sn, ignore.case = TRUE) && is.character(v) &&
          length(v) > 0L) {
        bad <- !is.na(v) & nzchar(v) & !v %in% c(tgt_tfs, "ANNUAL")
        if (any(bad)) {
          st$tf <<- c(st$tf, sprintf("%s@%s (%s)", nm_el, sn,
                                     paste(unique(v[bad]), collapse = ", ")))
          v[bad] <- finest
          methods::slot(el, sn) <- v
        }
      }
    }
    el
  }

  for (i in seq_along(object@data)) object@data[[i]] <- recast_el(object@data[[i]])

  object@config@calendar <- calendar
  # The recast is no longer the stored version it was built from, and
  # `save_model()` updates an entry in place BY NAME, so the parent's hash
  # would let it overwrite the source model's entry while claiming to be it.
  object@misc$hash <- NULL

  .say("recast onto calendar '", calendar@name, "' (", n_src, " -> ", n_tgt,
          " timeslices): ", st$tables, " table(s), ",
          format(st$rows_in, big.mark = ","), " -> ",
          format(st$rows_out, big.mark = ","), " row(s)",
          if (st$kept) paste0(", ", format(st$kept, big.mark = ","),
                              " row(s) kept at their declared timeframe")
          else "",
          if (length(st$tf)) paste0("; ", length(st$tf),
                                    " timeframe declaration(s) -> ", finest,
                                    if (isTRUE(verbose))
                                      paste0(": ", paste(st$tf, collapse = "; "))
                                    else " (verbose = TRUE lists them)")
          else "",
          ".\nDispatch, costs and the objective are the recast model's own, ",
          "not the source model's.")
  if (length(st$dropped)) {
    warning("the target calendar does not cover every source timeslice; ",
            "data was lost in ", length(unique(st$dropped)), " table(s): ",
            paste(unique(st$dropped), collapse = ", "), call. = FALSE)
  }
  object
}

# The timeframes of an energyRt calendar, coarsest first, ANNUAL dropped.
#' @noRd
.calendar_timeframes <- function(calendar) {
  tfs <- setdiff(names(calendar@timetable),
                 c("timeslice", "share", "weight", "ANNUAL"))
  if (!length(tfs)) "ANNUAL" else tfs
}

# The year both calendars are materialised on: the model's first milestone.
#' @noRd
.recast_year <- function(object) {
  h <- tryCatch(object@config@horizon, error = function(e) NULL)
  y <- tryCatch(as.integer(h@intervals$mid), error = function(e) integer())
  if (!length(y)) y <- tryCatch(as.integer(h@period), error = function(e) integer())
  if (!length(y) || all(is.na(y))) return(2025L)
  min(y, na.rm = TRUE)
}

# One table. Returns `NULL` data when there is nothing to do, so the caller can
# leave the slot alone and not count it.
#' @noRd
.recast_table <- function(d, ts_src, ts_tgt, src_leaves, rule_default, rules,
                          year, where) {
  num <- names(d)[vapply(d, is.numeric, logical(1))]
  values <- setdiff(num, c(.recast_id_cols, "timeslice"))
  if (!length(values)) return(list(data = NULL, kept = 0L, dropped = character(0)))
  tsl <- as.character(d[["timeslice"]])
  at_leaf <- !is.na(tsl) & tsl %in% src_leaves
  if (!any(at_leaf)) return(list(data = NULL, kept = 0L, dropped = character(0)))

  rule <- stats::setNames(rep(rule_default, length(values)), values)
  if (!is.null(rules)) {
    hit <- intersect(names(rules), values)
    rule[hit] <- unname(rules[hit])
  }

  src <- d[at_leaf, , drop = FALSE]
  src[["timeslice"]] <- tsl[at_leaf]
  dropped <- character(0)
  out <- withCallingHandlers(
    as.data.frame(timescales::recast_calendar(
      src, source = ts_src, target = ts_tgt, year = year,
      key = "timeslice", values = values, rule = rule[values])),
    warning = function(w) {
      if (grepl("not covered|were ignored", conditionMessage(w))) {
        dropped <<- c(dropped, where)
      }
      invokeRestart("muffleWarning")
    })
  # `recast_calendar()` returns the full target vocabulary, NA where the
  # target covers a slice the source never populated.
  out <- out[!is.na(out[["timeslice"]]), , drop = FALSE]
  keep_cols <- intersect(colnames(d), colnames(out))
  out <- out[, keep_cols, drop = FALSE]
  # A target timeslice the source never populated carries NA in every value
  # column and is not a row the object declared. A row with SOME values is
  # kept: energyRt tables routinely leave one bound of a pair empty.
  vcols <- intersect(values, keep_cols)
  if (length(vcols)) {
    has_value <- rowSums(!is.na(out[, vcols, drop = FALSE])) > 0L
    out <- out[has_value, , drop = FALSE]
  }
  if (all(at_leaf)) {
    return(list(data = out, kept = 0L, dropped = dropped))
  }
  rest <- d[!at_leaf, keep_cols, drop = FALSE]
  list(data = rbind(out, rest), kept = nrow(rest), dropped = dropped)
}
